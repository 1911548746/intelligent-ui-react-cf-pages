import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "src/generated/system-prompt.txt");
const target = resolve(root, "functions/_shared/system-prompt.generated.ts");
const prompt = await readFile(source, "utf8");
await mkdir(dirname(target), { recursive: true });
await writeFile(target, `// Generated by scripts/embed-system-prompt.mjs. Do not edit by hand.\nexport const SYSTEM_PROMPT = ${JSON.stringify(prompt)};\n`, "utf8");
console.log(`Embedded ${prompt.length.toLocaleString()} characters into ${target}`);
